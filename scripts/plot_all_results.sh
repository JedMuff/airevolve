#!/usr/bin/env bash
# =============================================================================
# plot_all_results.sh — Cross-experiment Pareto comparison plot
#
# Reads the final evolution_data.csv from every completed experiment run and
# produces a single overlay scatter plot at:
#   results/pareto_comparison_all.png
#
# Run this after all three experiment scripts have finished.
#
# Usage:
#   bash scripts/plot_all_results.sh [--results-dir DIR]
#
# Options:
#   --results-dir  Root directory containing experiment outputs (default: results/).
# =============================================================================

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RESULTS_DIR="${REPO_ROOT}/results"

# ── Parse flags ───────────────────────────────────────────────────────────────
while [[ $# -gt 0 ]]; do
    case "$1" in
        --results-dir) RESULTS_DIR="$2"; shift ;;
        *) echo "Unknown flag: $1" >&2; exit 1 ;;
    esac
    shift
done

PLOT_SCRIPT="${REPO_ROOT}/airevolve/evolution_tools/inspection_tools/plot_pareto_front.py"
OUTPUT="${RESULTS_DIR}/pareto_comparison_all.png"

# ── Expected CSV paths (one per experiment variant) ───────────────────────────
# These match the directory names generated by run_energy_ablation.py:
#   w=0   → exp_<type>_w_0
#   w>0   → exp_<type>_w_<python:.0e format>   e.g. 1e-05, 5e-05, 1e-03 …
declare -A CSV_FILES=(
    ["Baseline"]="${RESULTS_DIR}/exp_baseline_w_0/evolution_data.csv"
    ["Dense w=0"]="${RESULTS_DIR}/exp_dense_w_0/evolution_data.csv"
    ["Dense 1e-5"]="${RESULTS_DIR}/exp_dense_w_1e-05/evolution_data.csv"
    ["Dense 5e-5"]="${RESULTS_DIR}/exp_dense_w_5e-05/evolution_data.csv"
    ["Sparse w=0"]="${RESULTS_DIR}/exp_sparse_w_0/evolution_data.csv"
    ["Sparse 1e-3"]="${RESULTS_DIR}/exp_sparse_w_1e-03/evolution_data.csv"
    ["Sparse 4e-3"]="${RESULTS_DIR}/exp_sparse_w_4e-03/evolution_data.csv"
    ["Sparse 7e-3"]="${RESULTS_DIR}/exp_sparse_w_7e-03/evolution_data.csv"
)

# Maintain a fixed display order (bash associative arrays are unordered)
ORDERED_KEYS=(
    "Baseline"
    "Dense w=0" "Dense 1e-5" "Dense 5e-5"
    "Sparse w=0" "Sparse 1e-3" "Sparse 4e-3" "Sparse 7e-3"
)

# ── Collect only the CSVs that actually exist ─────────────────────────────────
PRESENT_CSVS=()
PRESENT_LABELS=()
MISSING=()

for key in "${ORDERED_KEYS[@]}"; do
    path="${CSV_FILES[$key]}"
    if [[ -f "${path}" ]]; then
        PRESENT_CSVS+=("${path}")
        PRESENT_LABELS+=("${key}")
    else
        MISSING+=("${key} (${path})")
    fi
done

if [[ ${#PRESENT_CSVS[@]} -eq 0 ]]; then
    echo "ERROR: No completed experiment CSVs found under ${RESULTS_DIR}." >&2
    echo "       Run the experiment scripts first." >&2
    exit 1
fi

if [[ ${#MISSING[@]} -gt 0 ]]; then
    echo "NOTE: The following experiments are not yet complete and will be skipped:"
    for m in "${MISSING[@]}"; do
        echo "  - ${m}"
    done
    echo ""
fi

echo "Generating Pareto comparison plot from ${#PRESENT_CSVS[@]} experiment(s)…"
echo "Output → ${OUTPUT}"

python "${PLOT_SCRIPT}" \
    "${PRESENT_CSVS[@]}" \
    --labels "${PRESENT_LABELS[@]}" \
    --output "${OUTPUT}" \
    --pareto-only \
    --title "Energy Ablation Study — All Experiments (Pareto Front)"

echo "Done."
