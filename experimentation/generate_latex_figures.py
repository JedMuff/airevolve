    add(_subsection("Hovering capability"))

    subfigs = _cross_task_subfigures(
        "morphological_descriptors", "hover_fitness",
        "Hover fitness — {task}", "hover_fitness",
    )
    all_exist = all(exists(s[0]) for s in subfigs)
    if all_exist:
        add(_grouped_figure(
            subfigs,
            "Hover fitness component across tasks. All representations "
            "achieve comparable hovering performance, confirming that "
            "fitness differences arise from trajectory-following rather "
            "than basic flight stability.",
            "morpho_hover_fitness",
            cols=3,
        ))
    else:
        for s in subfigs:
            if not exists(s[0]):
                skipped.append(s[0])

    # --- Gates passed ---
    add(_subsection("Task completion (gates passed)"))

    subfigs = _cross_task_subfigures(
        "morphological_descriptors", "gates_passed",
        "Gates passed — {task}", "gates_passed",
    )
    all_exist = all(exists(s[0]) for s in subfigs)
    if all_exist:
        add(_grouped_figure(
            subfigs,
            "Number of trajectory gates passed at the final generation. "
            "The Hybrid representation completes significantly more "
            "of the prescribed trajectory than both alternatives.",
            "morpho_gates_passed",
            cols=3,
        ))
    else:
        for s in subfigs:
            if not exists(s[0]):
                skipped.append(s[0])

    # ═════════════════════════════════════════════════════════════════════════
    # SECTION 3: DIVERSITY ANALYSIS
    # ═════════════════════════════════════════════════════════════════════════
    add(_section("SECTION: DIVERSITY ANALYSIS"))

    # --- 3a. Genotypic vs phenotypic diversity correlation ---
    add(_subsection("Genotypic--phenotypic diversity relationship"))

    for task in TASKS:
        task_label = TASK_LABELS[task]
        tk = _sanitize(task)
        subfigs = []
        for geno, geno_label in [("spherical", "Spherical"),
                                  ("cppn", "CPPN"),
                                  ("hybrid_cppn", "Hybrid")]:
            path = _fig(task, "genome_diversity",
                        f"genotypic_vs_phenotypic_{geno}")
            subfigs.append((
                path,
                geno_label,
                f"gvp_{tk}_{_sanitize(geno)}",
                "0.32",
            ))
        all_exist = all(exists(s[0]) for s in subfigs)
        if all_exist:
            add(_grouped_figure(
                subfigs,
                f"Genotypic vs.\\ phenotypic diversity for the {task_label} "
                f"task. Spherical shows perfect correlation ($r=1.0$) since "
                f"genotype directly encodes phenotype. CPPN and Hybrid show "
                f"near-zero correlation, indicating genotypic neutrality in "
                f"indirect encodings.",
                f"gvp_{tk}",
                cols=3,
            ))
        else:
            for s in subfigs:
                if not exists(s[0]):
                    skipped.append(s[0])

    # --- 3b. Cross-task genome diversity comparison ---
    add(_subsection("Genome diversity across tasks"))

    path = _cross("genome_diversity", "genome_diversity_cross_task")
    add_if(path, _figure(
        path,
        "Genotypic diversity at the final generation across tasks. "
        "CPPN maintains the highest genotypic diversity, but this does "
        "not translate to superior fitness. Hybrid achieves the lowest "
        "genotypic diversity yet the best performance, suggesting "
        "efficient convergence to good solutions.",
        "genome_diversity_cross_task",
    ))

    # --- 3c. Phenotypic diversity curves per task ---
    add(_subsection("Phenotypic diversity evolution"))

    subfigs = _cross_task_subfigures(
        "fitness_diversity", "diversity",
        "Phenotypic diversity — {task}", "pheno_div",
    )
    all_exist = all(exists(s[0]) for s in subfigs)
    if all_exist:
        add(_grouped_figure(
            subfigs,
            "Phenotypic (edit distance) diversity over generations. CPPN "
            "maintains significantly higher phenotypic diversity than both "
            "alternatives (large effect, $p < 0.0001$).",
            "phenotypic_diversity_all",
            cols=3,
        ))
    else:
        for s in subfigs:
            if not exists(s[0]):
                skipped.append(s[0])

    # --- 3d. Genome diversity curves per task ---
    add(_subsection("Genotypic diversity evolution"))

    subfigs = _cross_task_subfigures(
        "genome_diversity", "genome_diversity_over_generations",
        "Genome diversity — {task}", "geno_div",
    )
    all_exist = all(exists(s[0]) for s in subfigs)
    if all_exist:
        add(_grouped_figure(
            subfigs,
            "Genotypic diversity over generations. Spherical starts high "
            "(random initialisation covers the parameter space) and declines, "
            "while CPPN diversity grows as network topologies diverge.",
            "genotypic_diversity_all",
            cols=3,
        ))
    else:
        for s in subfigs:
            if not exists(s[0]):
                skipped.append(s[0])

    # ═════════════════════════════════════════════════════════════════════════
    # SECTION 4: INTER-RUN DIVERGENCE AND REPRODUCIBILITY
    # ═════════════════════════════════════════════════════════════════════════
    add(_section("SECTION: INTER-RUN DIVERGENCE"))

    # --- Divergence ratio heatmap ---
    add(_subsection("Cross-task divergence ratio"))

    path = _cross("inter_run_diversity", "divergence_ratio_heatmap")
    add_if(path, _figure(
        path,
        "Inter-run divergence ratio across tasks and representations. "
        "Higher values indicate that independent runs converge to more "
        "diverse final populations. Spherical shows the highest "
        "inter-run divergence ($\\approx 3.5$), suggesting sensitivity "
        "to initial conditions, while CPPN shows the lowest "
        "($\\approx 1.5$).",
        "divergence_heatmap",
    ))

    # --- Top-K cross-run diversity ---
    path = _cross("top_k_diversity", "top_k_diversity_comparison")
    add_if(path, _figure(
        path,
        "Mean phenotypic distance among the top-$k$ individuals from "
        "independent runs. Higher values indicate that each run discovers "
        "distinct high-quality solutions. Hybrid produces the most diverse "
        "elite solutions across runs.",
        "top_k_diversity",
    ))

    # --- Per-task divergence curves ---
    add(_subsection("Divergence ratio evolution"))

    subfigs = _cross_task_subfigures(
        "inter_run_diversity", "divergence_ratio_over_generations",
        "Divergence ratio — {task}", "div_ratio",
    )
    all_exist = all(exists(s[0]) for s in subfigs)
    if all_exist:
        add(_grouped_figure(
            subfigs,
            "Inter-run divergence ratio over generations. Spherical "
            "diverges most, indicating it finds qualitatively different "
            "local optima across runs.",
            "divergence_ratio_all",
            cols=3,
        ))
    else:
        for s in subfigs:
            if not exists(s[0]):
                skipped.append(s[0])

    # ═════════════════════════════════════════════════════════════════════════
    # SECTION 5: CPPN NETWORK COMPLEXITY
    # ═════════════════════════════════════════════════════════════════════════
    add(_section("SECTION: CPPN NETWORK COMPLEXITY"))

    add(_subsection("Network complexity per task"))

    for task in TASKS:
        task_label = TASK_LABELS[task]
        tk = _sanitize(task)
        subfigs = [
            (_fig(task, "genotypic_descriptors",
                  "n_hidden_nodes_over_generations"),
             "Hidden nodes", f"hidden_{tk}", "0.32"),
            (_fig(task, "genotypic_descriptors",
                  "n_enabled_connections_over_generations"),
             "Enabled connections", f"connections_{tk}", "0.32"),
            (_fig(task, "genotypic_descriptors",
                  "connection_density_over_generations"),
             "Connection density", f"density_{tk}", "0.32"),
        ]
        all_exist = all(exists(s[0]) for s in subfigs)
        if all_exist:
            add(_grouped_figure(
                subfigs,
                f"CPPN network complexity over generations for the "
                f"{task_label} task. Pure CPPN evolves more complex "
                f"networks than Hybrid, which offloads arm geometry to "
                f"the direct encoding.",
                f"cppn_complexity_{tk}",
                cols=3,
            ))
        else:
            for s in subfigs:
                if not exists(s[0]):
                    skipped.append(s[0])

    # Cross-task summary
    add(_subsection("Cross-task network complexity"))

    cross_geno = [
        ("n_hidden_nodes_cross_task", "Hidden nodes"),
        ("n_enabled_connections_cross_task", "Enabled connections"),
        ("longest_path_cross_task", "Longest path"),
    ]
    subfigs = []
    for filename, sub_cap in cross_geno:
        path = _cross("genotypic_descriptors", filename)
        subfigs.append((
            path,
            sub_cap,
            f"cross_{_sanitize(filename)}",
            "0.32",
        ))
    all_exist = all(exists(s[0]) for s in subfigs)
    if all_exist:
        add(_grouped_figure(
            subfigs,
            "CPPN network complexity at the final generation across tasks. "
            "Hybrid uses significantly simpler networks (fewer hidden nodes "
            "and connections) than pure CPPN, demonstrating that the direct "
            "encoding component reduces the burden on the neural network.",
            "cppn_complexity_cross",
            cols=3,
        ))
    else:
        for s in subfigs:
            if not exists(s[0]):
                skipped.append(s[0])

    # ═════════════════════════════════════════════════════════════════════════
    # SECTION 6: BLOODLINE ANALYSIS
    # ═════════════════════════════════════════════════════════════════════════
    add(_section("SECTION: BLOODLINE ANALYSIS"))

    subfigs = _cross_task_subfigures(
        "bloodline", "bloodline_divergence_over_generations",
        "Bloodline divergence — {task}", "bloodline_div",
    )
    all_exist = all(exists(s[0]) for s in subfigs)
    if all_exist:
        add(_grouped_figure(
            subfigs,
            "Phenotypic divergence of the surviving bloodline from its "
            "founder over generations. CPPN lineages accumulate the most "
            "phenotypic change, while Spherical lineages remain closest "
            "to their founders, consistent with the direct encoding's "
            "smaller mutational steps.",
            "bloodline_divergence_all",
            cols=3,
        ))
    else:
        for s in subfigs:
            if not exists(s[0]):
                skipped.append(s[0])

    # ═════════════════════════════════════════════════════════════════════════
    # SECTION 7: CONVERGENCE SPEED (brief — mostly non-significant)
    # ═════════════════════════════════════════════════════════════════════════
    add(_section("SECTION: CONVERGENCE SPEED (SUPPLEMENTARY)"))

    add(_subsection("Generation to fitness thresholds"))

    subfigs = _cross_task_subfigures(
        "convergence_speed", "gen_to_threshold",
        "Generations to threshold — {task}", "conv_thresh",
    )
    all_exist = all(exists(s[0]) for s in subfigs)
    if all_exist:
        add(_grouped_figure(
            subfigs,
            "Generations required to reach 50\\%, 75\\%, and 90\\% of "
            "final fitness. No significant differences were found between "
            "representations, indicating that the Hybrid's advantage lies "
            "in the quality of its final solutions rather than convergence "
            "speed.",
            "convergence_thresholds",
            cols=3,
        ))
    else:
        for s in subfigs:
            if not exists(s[0]):
                skipped.append(s[0])

    # Normalised AUC
    add(_subsection("Normalised area under the fitness curve"))

    subfigs = _cross_task_subfigures(
        "convergence_speed", "auc_normalized",
        "Normalised AUC — {task}", "auc",
    )
    all_exist = all(exists(s[0]) for s in subfigs)
    if all_exist:
        add(_grouped_figure(
            subfigs,
            "Normalised area under the fitness curve. Values near 1.0 "
            "indicate rapid convergence to the final fitness level.",
            "auc_all",
            cols=3,
        ))
    else:
        for s in subfigs:
            if not exists(s[0]):
                skipped.append(s[0])

