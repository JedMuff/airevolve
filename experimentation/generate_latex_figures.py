#!/usr/bin/env python3
"""Generate LaTeX figure and table code for a paper comparing three
drone morphology representations (Spherical, CPPN, Hybrid).

Produces a curated, paper-structured .tex file organised by narrative
section rather than a flat dump of every generated plot.

Usage:
    python -m experimentation.generate_latex_figures
    python -m experimentation.generate_latex_figures --base-dir /path/to/data
"""

import argparse
import os

from experimentation.config import BASE_DIR, TASK_LABELS

# ── Ordered task list (controls figure ordering) ─────────────────────────────
TASKS = ["backandforth", "figure8", "circle"]

# ── Helper paths ─────────────────────────────────────────────────────────────

def _fig(task, plotter, name):
    """Return relative PDF path for a figure."""
    return f"figures/{task}/{plotter}/{name}.pdf"


def _cross(plotter, name):
    """Return relative PDF path for a cross-task figure."""
    return _fig("cross_task", plotter, name)


# ── LaTeX building blocks ────────────────────────────────────────────────────

def _sanitize(s):
    return s.replace(" ", "_").replace("/", "_").replace("-", "_").lower()


def _subfig(path, caption, width, label):
    return (
        f"    \\begin{{subfigure}}{{{width}\\textwidth}}\n"
        f"        \\centering\n"
        f"        \\includegraphics[width=\\textwidth]{{{path}}}\n"
        f"        \\caption{{{caption}}}\n"
        f"        \\label{{fig:{label}}}\n"
        f"    \\end{{subfigure}}"
    )


def _figure(path, caption, label, width="0.85\\textwidth"):
    return (
        f"\\begin{{figure}}[htbp]\n"
        f"    \\centering\n"
        f"    \\includegraphics[width={width}]{{{path}}}\n"
        f"    \\caption{{{caption}}}\n"
        f"    \\label{{fig:{label}}}\n"
        f"\\end{{figure}}"
    )


def _input_table(path, caption, label):
    """Input an external .tex significance table with surrounding table env."""
    return (
        f"\\begin{{table}}[htbp]\n"
        f"    \\centering\n"
        f"    \\caption{{{caption}}}\n"
        f"    \\label{{tab:{label}}}\n"
        f"    \\input{{{path}}}\n"
        f"\\end{{table}}"
    )


def _grouped_figure(subfigs, caption, label, cols=3):
    """Build a figure environment with multiple subfigures."""
    lines = [
        "\\begin{figure*}[htbp]",
        "    \\centering",
    ]
    for i, (path, sub_caption, sub_label, width) in enumerate(subfigs):
        lines.append(_subfig(path, sub_caption, width, sub_label))
        if (i + 1) % cols == 0 and i + 1 < len(subfigs):
            lines.append("    \\\\[6pt]")
        elif i + 1 < len(subfigs):
            lines.append("    \\hfill")
    lines.append(f"    \\caption{{{caption}}}")
    lines.append(f"    \\label{{fig:{label}}}")
    lines.append("\\end{figure*}")
    return "\n".join(lines)


def _cross_task_subfigures(plotter, filename, _caption_template, label_prefix,
                           width="0.32"):
    """Create a 3-subfigure row: one per task."""
    subfigs = []
    for task in TASKS:
        task_label = TASK_LABELS[task]
        path = _fig(task, plotter, filename)
        subfigs.append((
            path,
            task_label,
            f"{label_prefix}_{_sanitize(task)}",
            width,
        ))
    return subfigs


def _section(title):
    return f"\n% {'=' * 70}\n% {title}\n% {'=' * 70}\n"


def _subsection(title):
    return f"\n% ── {title} {'─' * max(1, 60 - len(title))}\n"


# ── File existence checker ───────────────────────────────────────────────────

def _exists(base, relpath):
    """Check whether a figure PDF exists on disk."""
    return os.path.isfile(os.path.join(base, "output", relpath))


# ── Main generator ───────────────────────────────────────────────────────────

def generate_latex(base_dir=None):
    """Generate a curated, paper-structured LaTeX file."""
    base = base_dir or BASE_DIR
    figures_root = os.path.join(base, "output", "figures")

    if not os.path.isdir(figures_root):
        print(f"No figures directory found at {figures_root}")
        return

    def exists(relpath):
        return _exists(base, relpath)

    lines = [
        "% Auto-generated by generate_latex_figures.py",
        "% Paper-structured LaTeX for: Comparing Drone Morphology Representations",
        "% Include with: \\input{paper_figures.tex}",
        "%",
        "% Requires packages: graphicx, subcaption, booktabs",
        "",
    ]
    skipped = []

    def add(text):
        lines.append(text)
        lines.append("")

    def add_if(relpath, text):
        if exists(relpath):
            add(text)
        else:
            skipped.append(relpath)

    # ═════════════════════════════════════════════════════════════════════════
    # SECTION 1: FITNESS RESULTS (the core result)
    # ═════════════════════════════════════════════════════════════════════════
    add(_section("SECTION: FITNESS RESULTS"))

    # --- 1a. Fitness curves across tasks (max + mean + diversity) ---
    add(_subsection("Fitness and diversity evolution per task"))

    for task in TASKS:
        task_label = TASK_LABELS[task]
        tk = _sanitize(task)

        subfigs = [
            (_fig(task, "fitness_diversity", "max_fitness"),
             "Maximum fitness", f"max_fitness_{tk}", "0.32"),
            (_fig(task, "fitness_diversity", "mean_fitness"),
             "Mean fitness", f"mean_fitness_{tk}", "0.32"),
            (_fig(task, "fitness_diversity", "diversity"),
             "Phenotypic diversity", f"diversity_{tk}", "0.32"),
        ]
        all_exist = all(exists(s[0]) for s in subfigs)
        if all_exist:
            add(_grouped_figure(
                subfigs,
                f"Fitness and phenotypic diversity over generations for the "
                f"{task_label} task. Shaded regions show interquartile range "
                f"across independent runs.",
                f"fitness_diversity_{tk}",
                cols=3,
            ))
        else:
            for s in subfigs:
                if not exists(s[0]):
                    skipped.append(s[0])

    # --- 1b. Median max fitness box plots per task ---
    add(_subsection("Final generation fitness box plots"))

    subfigs = _cross_task_subfigures(
        "fitness_diversity", "median_max_fitness",
        "Median max fitness — {task}", "median_max",
    )
    all_exist = all(exists(s[0]) for s in subfigs)
    if all_exist:
        add(_grouped_figure(
            subfigs,
            "Distribution of per-run maximum fitness at the final generation "
            "across tasks. The Hybrid representation achieves the highest "
            "median and lowest variance.",
            "median_max_fitness_all",
            cols=3,
        ))
    else:
        for s in subfigs:
            if not exists(s[0]):
                skipped.append(s[0])

    # --- 1c. Cross-task significance tables ---
    add(_subsection("Cross-task statistical significance"))

    sig_path = "figures/cross_task/fitness_diversity/cross_task_significance.tex"
    add_if(sig_path, _input_table(
        sig_path,
        "Cross-task pairwise significance tests (Fisher's combined $p$-values "
        "with Bonferroni correction). The Hybrid representation significantly "
        "outperforms both Spherical and CPPN on mean fitness.",
        "cross_task_significance",
    ))

    # Per-task significance tables
    for task in TASKS:
        task_label = TASK_LABELS[task]
        tk = _sanitize(task)
        path = f"figures/{task}/fitness_diversity/significance_table.tex"
        add_if(path, _input_table(
            path,
            f"Pairwise significance tests for fitness metrics — "
            f"{task_label} task.",
            f"significance_{tk}",
        ))

    # ═════════════════════════════════════════════════════════════════════════
    # SECTION 2: WHY HYBRID WINS — MORPHOLOGICAL DESCRIPTORS
    # ═════════════════════════════════════════════════════════════════════════
    add(_section("SECTION: MORPHOLOGICAL ANALYSIS"))

    # Key descriptors that explain the fitness advantage
    key_morpho = [
        ("thrust_alignment",
         "Thrust alignment",
         "Number of motors with thrust vectors aligned to the body $z$-axis. "
         "Higher values indicate more motors contributing to vertical lift."),
        ("max_thrust_to_weight",
         "Thrust-to-weight ratio",
         "Maximum thrust-to-weight ratio. Designs below 1.0 cannot sustain "
         "hover. The Spherical representation evolves significantly lower "
         "ratios."),
        ("proportion",
         "Arm proportion",
         "Ratio of mean arm length to body radius. Longer arms provide "
         "greater control authority through increased moment arms."),
        ("controlability",
         "Controllability",
         "Condition number of the allocation matrix (lower is better). "
         "Hybrid and CPPN designs are significantly more controllable "
         "than Spherical."),
        ("f_force",
         "Force utilisation",
         "Fraction of maximum motor force aligned with the body $z$-axis. "
         "Values near 1.0 indicate well-oriented motor configurations."),
        ("f_torque",
         "Torque capability",
         "Fraction of motor force available for yaw torque generation. "
         "Lower values indicate more force dedicated to lift."),
    ]

    add(_subsection("Key morphological descriptors per task"))

    for filename, short_name, long_caption in key_morpho:
        subfigs = _cross_task_subfigures(
            "morphological_descriptors", filename,
            f"{short_name} — {{task}}", _sanitize(filename),
        )
        all_exist = all(exists(s[0]) for s in subfigs)
        if all_exist:
            add(_grouped_figure(
                subfigs,
                f"{long_caption}",
                f"morpho_{_sanitize(filename)}",
                cols=3,
            ))
        else:
            for s in subfigs:
                if not exists(s[0]):
                    skipped.append(s[0])

    # --- Symmetry descriptors ---
    add(_subsection("Symmetry descriptors"))

    for filename, short_name in [
        ("bilateral_asymmetry", "Bilateral asymmetry"),
        ("central_asymmetry", "Central asymmetry"),
    ]:
        subfigs = _cross_task_subfigures(
            "morphological_descriptors", filename,
            f"{short_name} — {{task}}", _sanitize(filename),
        )
        all_exist = all(exists(s[0]) for s in subfigs)
        if all_exist:
            add(_grouped_figure(
                subfigs,
                f"{short_name} over generations across tasks. CPPN-based "
                f"representations produce higher central asymmetry due to "
                f"position-dependent motor configurations.",
                f"morpho_{_sanitize(filename)}",
                cols=3,
            ))
        else:
            for s in subfigs:
                if not exists(s[0]):
                    skipped.append(s[0])

